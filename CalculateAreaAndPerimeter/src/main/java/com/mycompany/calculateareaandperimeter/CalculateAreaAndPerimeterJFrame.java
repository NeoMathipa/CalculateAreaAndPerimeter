    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:
        double area, perim, length, width;
        length = Double.parseDouble(this.txtLength.getText());
        width = Double.parseDouble(this.txtWidth.getText());
        area = length * width;
        perim = 2 * (length + width);
        
        this.txtTotalArea.setText(String.format("%.2f", area));
        this.txtTotalPerimeter.setText(String.format("%.2f", perim));
    }//GEN-LAST:event_btnSubmitActionPerformed

